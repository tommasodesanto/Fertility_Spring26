options(warn=2)
library(data.table)
library(fixest)
library(haven)
library(ggplot2)
setDTthreads(1); setFixest_nthreads(1)
stopifnot(grepl("aarch64|arm64", R.version$arch))
set.seed(20260919)
d <- data.table(id=rep(1:20, each=5), x=rnorm(100), noise=rnorm(100))
d[, y := 2*x + id + noise]
f <- feols(y ~ x | id, data=d, cluster=~id)
f_ref <- lm(y ~ x + factor(id), data=d)
stopifnot(abs(coef(f)["x"]-coef(f_ref)["x"]) < 1e-10)
p <- "output/setup/laptop_20260919/r/smoke.dta"
write_dta(as.data.frame(d),p)
d2 <- read_dta(p)
stopifnot(max(abs(d$x-as.numeric(d2$x))) < 1e-12, max(abs(d$y-as.numeric(d2$y))) < 1e-12)
png("output/setup/laptop_20260919/r/smoke.png",width=640,height=480)
print(ggplot(d,aes(x,y))+geom_point())
dev.off()
geom <- sf::st_sfc(sf::st_point(c(-74,40.7)), crs=4326)
stopifnot(all(is.finite(sf::st_coordinates(sf::st_transform(geom,3857)))))
raw <- haven::read_dta("code/data/attom_sample/assessor_history.dta", n_max=5)
stopifnot(nrow(raw)==5)
cat("FERTILITY_R_SMOKE_PASS: native ARM, fixed effects, clustered SE, Stata roundtrip, PNG, spatial transform, real-data read\n")
